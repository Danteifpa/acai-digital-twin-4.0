-- AçaíThermal Twin — esquema do banco (Supabase/Postgres)
-- Escritas: somente o motor (chave service_role, que ignora RLS).
-- Leitura: pública (anon) para o painel e o Realtime.

create table if not exists leituras_sensores (
    id bigint generated by default as identity primary key,
    lote_id text not null,
    temp_banho_c float8 not null,
    registrado_em timestamptz not null default now()
);

create table if not exists estado_digital_twin (
    id bigint generated by default as identity primary key,
    leitura_origem_id bigint references leituras_sensores(id) on delete set null,
    lote_id text not null,
    tempo_decorrido_s float8 not null,
    temp_banho_c float8,
    temp_superficie_c float8 not null,
    temp_centro_c float8 not null,
    tempo_letal_superficie_s float8 not null default 0,
    taxa_inativacao_pct float8 not null,
    retencao_antocianinas_pct float8 not null,
    energia_absorvida_kj_kg float8,
    previsao_corte_s float8,
    acao_recomendada text,
    perfil_radial_c jsonb,
    status_processo text not null,
    calculado_em timestamptz not null default now()
);

-- Migração de bancos criados com a versão anterior
alter table estado_digital_twin add column if not exists temp_banho_c float8;
alter table estado_digital_twin add column if not exists tempo_letal_superficie_s float8 not null default 0;
alter table estado_digital_twin add column if not exists energia_absorvida_kj_kg float8;
alter table estado_digital_twin add column if not exists previsao_corte_s float8;
alter table estado_digital_twin add column if not exists acao_recomendada text;
alter table estado_digital_twin add column if not exists perfil_radial_c jsonb;

create index if not exists idx_estado_lote_tempo on estado_digital_twin (lote_id, tempo_decorrido_s);
create index if not exists idx_leituras_lote on leituras_sensores (lote_id, registrado_em);

-- Row Level Security: sem políticas de escrita, a chave anon/publishable não grava nada.
alter table leituras_sensores enable row level security;
alter table estado_digital_twin enable row level security;

drop policy if exists "leitura publica" on leituras_sensores;
create policy "leitura publica" on leituras_sensores for select to anon, authenticated using (true);

drop policy if exists "leitura publica" on estado_digital_twin;
create policy "leitura publica" on estado_digital_twin for select to anon, authenticated using (true);

-- Realtime para o painel
do $$
begin
  alter publication supabase_realtime add table estado_digital_twin;
exception when duplicate_object or undefined_object then null;
end $$;
