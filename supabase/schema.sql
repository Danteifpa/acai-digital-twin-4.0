create table if not exists leituras_sensores (
    id bigint generated by default as identity primary key,
    lote_id text not null,
    temp_banho_c float8 not null,
    registrado_em timestamp with time zone default timezone('utc'::text, now())
);

create table if not exists estado_digital_twin (
    id bigint generated by default as identity primary key,
    leitura_origem_id bigint references leituras_sensores(id),
    lote_id text not null,
    tempo_decorrido_s float8 not null,
    temp_superficie_c float8 not null,
    temp_centro_c float8 not null,
    taxa_inativacao_pct float8 not null,
    retencao_antocianinas_pct float8 not null,
    status_processo text not null,
    calculado_em timestamp with time zone default timezone('utc'::text, now())
);